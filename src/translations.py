def get_translation(language: str, key: str, **kwargs) -> str:
    """
    Obtiene una traducción para el idioma especificado.
    
    Args:
        language: Código de idioma (en, es, fr, it, de, zh)
        key: Clave de traducción
        **kwargs: Parámetros para formatear el string
        
    Returns:
        String traducido y formateado
    """
    # Si el idioma no existe, usar inglés por defecto
    if language not in TRANSLATIONS:
        language = "en"
    
    # Si la clave no existe, retornar la clave misma
    translation = TRANSLATIONS[language].get(key, key)
    
    # Formatear con parámetros si se proporcionan
    if kwargs:
        try:
            translation = translation.format(**kwargs)
        except KeyError:
            pass
    
    return translation
